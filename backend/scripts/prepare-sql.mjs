import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const names = ["202610220001_backend_abuse_controls.sql", "202610220002_safe_media_cleanup.sql"];
const parts = await Promise.all(names.map(async name => (await readFile(path.join(root, "supabase/migrations", name), "utf8"))
  .replace(/^\s*(?:begin|commit);\s*$/gim, "").trim()));
const header = `-- SQL Editor: security + safe media cleanup, 22/10/2026.
-- PREREQUISITE: configure SUPABASE_SECRET_KEY only in backend and a strong
-- WISH_RATE_LIMIT_SECRET on EVERY backend using this database, including dev.
-- Anonymous submission RPCs are revoked; missing backend key will block wishes.
-- If only enabling photo cleanup, run migration 202610220002 by itself instead.
-- Requires earlier application migrations. Does not delete any existing files.
-- Generated by node scripts/prepare-sql.mjs; all changes run in one transaction.
`;
const destination = path.join(root, "supabase/sql-editor/20261022_security_and_media.sql");
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, `${header}\nbegin;\n\n${parts.join("\n\n")}\n\ncommit;\n`, "utf8");
console.log("Prepared supabase/sql-editor/20261022_security_and_media.sql");
